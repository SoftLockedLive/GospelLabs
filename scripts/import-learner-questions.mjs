#!/usr/bin/env node
/**
 * Converts the learner-question survey export (Google Forms → .xlsx) into
 * data/private/learner-questions.json, preserving every response verbatim
 * with its row number and timestamp, and writes data/private/BACKLOG.md:
 * the categorized backlog for future content, grouped by the families in
 * src/content/learner-questions/families.json.
 *
 * data/private/ is git-ignored: the survey is anonymous, but some responses
 * are personal, and the repository is public. Only theme families and row
 * numbers are committed.
 *
 * Usage: node scripts/import-learner-questions.mjs "<path to .xlsx>"
 * No dependencies: reads the .xlsx (a zip of XML files) with Node's zlib.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { inflateRawSync } from "node:zlib";

const [input] = process.argv.slice(2);
if (!input) {
  console.error('Usage: node scripts/import-learner-questions.mjs "<path to .xlsx>"');
  process.exit(1);
}

/** Minimal zip reader: returns { name → Buffer } for stored and deflated entries. */
function unzip(buffer) {
  const eocd = buffer.lastIndexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]));
  if (eocd < 0) throw new Error("Not a zip file");
  const count = buffer.readUInt16LE(eocd + 10);
  let offset = buffer.readUInt32LE(eocd + 16);
  const files = {};
  for (let i = 0; i < count; i++) {
    const method = buffer.readUInt16LE(offset + 10);
    const compressedSize = buffer.readUInt32LE(offset + 20);
    const nameLength = buffer.readUInt16LE(offset + 28);
    const extraLength = buffer.readUInt16LE(offset + 30);
    const commentLength = buffer.readUInt16LE(offset + 32);
    const localOffset = buffer.readUInt32LE(offset + 42);
    const name = buffer.toString("utf8", offset + 46, offset + 46 + nameLength);
    const localNameLength = buffer.readUInt16LE(localOffset + 26);
    const localExtraLength = buffer.readUInt16LE(localOffset + 28);
    const start = localOffset + 30 + localNameLength + localExtraLength;
    const data = buffer.subarray(start, start + compressedSize);
    files[name] = method === 0 ? data : inflateRawSync(data);
    offset += 46 + nameLength + extraLength + commentLength;
  }
  return files;
}

const decode = (s) =>
  s.replace(/&(#x?[0-9a-f]+|amp|lt|gt|quot|apos);/gi, (_, e) =>
    e[0] === "#" ? String.fromCodePoint(parseInt(e.slice(e[1] === "x" ? 2 : 1), e[1] === "x" ? 16 : 10)) : { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'" }[e.toLowerCase()],
  );

const files = unzip(await readFile(input));
const shared = [...files["xl/sharedStrings.xml"].toString("utf8").matchAll(/<si>([\s\S]*?)<\/si>/g)].map(([, si]) =>
  decode([...si.matchAll(/<t[^>]*>([\s\S]*?)<\/t>/g)].map(([, t]) => t).join("")),
);
const sheet = files["xl/worksheets/sheet1.xml"].toString("utf8");

const rows = [];
for (const [, rowNumber, body] of sheet.matchAll(/<row[^>]*r="(\d+)"[^>]*>([\s\S]*?)<\/row>/g)) {
  const cells = {};
  for (const [, ref, attrs, inner] of body.matchAll(/<c r="([A-Z]+)\d+"([^>]*)>([\s\S]*?)<\/c>/g)) {
    const value = /<v>([\s\S]*?)<\/v>/.exec(inner)?.[1];
    if (value === undefined) continue;
    cells[ref] = /t="s"/.test(attrs) ? shared[Number(value)] : decode(value);
  }
  rows.push({ row: Number(rowNumber), cells });
}

/** Excel serial date (days since 1899-12-30, local time of the form) → "YYYY-MM-DDTHH:MM:SS". */
function excelDate(serial) {
  const ms = Math.round((Number(serial) - 25569) * 86400) * 1000;
  return new Date(ms).toISOString().slice(0, 19);
}

const [header, ...responses] = rows;
const dataset = {
  source: "Gospel Question (Responses).xlsx — Google Form export, sheet “Form Responses 1”",
  importedAt: new Date().toISOString(),
  columns: [header.cells.A, header.cells.B],
  note: "Verbatim, including spelling. Timestamps are the form's local time (no time zone). The form collected no names.",
  responses: responses.map(({ row, cells }) => ({
    row,
    submittedAt: cells.A ? excelDate(cells.A) : null,
    text: cells.B ?? "",
  })),
};

const families = JSON.parse(await readFile(new URL("../src/content/learner-questions/families.json", import.meta.url), "utf8"));
const byRow = new Map(dataset.responses.map((response) => [response.row, response]));
const assigned = new Set(families.families.flatMap((family) => family.rows));
const unassigned = dataset.responses.filter((response) => !assigned.has(response.row)).map((response) => response.row);

let backlog = `# Learner-question backlog (private)\n\nGenerated by scripts/import-learner-questions.mjs from ${dataset.source}.\n${dataset.responses.length} responses. Verbatim. Do not commit this file.\n`;
for (const family of families.families) {
  backlog += `\n## ${family.label} (${family.rows.length})\n\n${family.description}\n\n`;
  if (family.investigation) backlog += `**Gospel Labs 2.0 investigation:** \`${family.investigation}\`\n\n`;
  for (const row of family.rows) backlog += `- [row ${row}] ${byRow.get(row)?.text.trim() ?? "(missing)"}\n`;
}
if (unassigned.length) backlog += `\n## Unassigned (${unassigned.length})\n\n${unassigned.map((row) => `- [row ${row}] ${byRow.get(row)?.text.trim()}`).join("\n")}\n`;

await mkdir(new URL("../data/private/", import.meta.url), { recursive: true });
await writeFile(new URL("../data/private/learner-questions.json", import.meta.url), `${JSON.stringify(dataset, null, 2)}\n`);
await writeFile(new URL("../data/private/BACKLOG.md", import.meta.url), backlog);
console.log(`${dataset.responses.length} responses → data/private/learner-questions.json and data/private/BACKLOG.md`);
if (unassigned.length) console.log(`Rows not assigned to a family: ${unassigned.join(", ")}`);
