#!/usr/bin/env node
/**
 * Collects every `review` section in src/content/ into one Markdown report
 * for the project owner's doctrinal review: docs/2.0/DOCTRINAL_REVIEW.md.
 * Items marked needs-review come first. Regenerate after editing content:
 *
 *   node scripts/review-notes.mjs
 */
import { readdir, readFile, writeFile } from "node:fs/promises";

const root = new URL("../src/content/", import.meta.url);
const groups = [
  ["investigations/", "Investigations", (d) => `${d.title} — “${d.question}”`],
  ["attributes/", "Character of Christ attributes", (d) => d.name],
  ["passages/", "Scripture Explorer passages", (d) => d.title],
];

const entries = [];
for (const [dir, group, title] of groups) {
  for (const name of (await readdir(new URL(dir, root))).filter((n) => n.endsWith(".json")).sort()) {
    const data = JSON.parse(await readFile(new URL(`${dir}${name}`, root), "utf8"));
    if (data.placeholder || !data.review) continue;
    entries.push({ group, file: `src/content/${dir}${name}`, title: title(data), status: data.review.status, notes: data.review.notes ?? [] });
  }
}

const needs = entries.filter((e) => e.status === "needs-review");
const verified = entries.filter((e) => e.status !== "needs-review");
const totalNotes = entries.reduce((sum, e) => sum + e.notes.length, 0);

let md = `# Doctrinal review list

Generated by \`node scripts/review-notes.mjs\` from the \`review\` section of every content file. Regenerate after editing content.

Every quotation, verse, and link in this content passed \`npm run verify:study\` (checked word for word against ChurchofJesusChrist.org and BYU Speeches). Automated checks confirm that quoted words are real and links open the intended pages; they **cannot** confirm that an interpretation is sound. The notes below are where the authors made interpretive choices, relied on a speaker rather than scripture or official resources, or touched sensitive topics. They're grouped by item, with items marked **needs-review** first.

- Items: ${entries.length} (${needs.length} marked needs-review, ${verified.length} verified with notes)
- Notes: ${totalNotes}

Before the 2.0 release every note was given a **resolution**:
- **Resolved:** a straightforward wording or citation fix, using verified sources.
- **Qualified:** an interpretation now clearly framed as one ("one way to read this", "Gospel Labs suggests", "Elder X taught").
- **Withheld:** removed until the owner reviews it; the original is kept in \`docs/2.0/withheld/\`.

Items still marked **needs-review** are safe to ship as qualified, but the owner should still confirm them. To finish an item: edit the content file, set \`review.status\` to \`verified\`, rerun \`npm run verify:study\` and \`npm test\`, and regenerate this file.

Connect with Christ sessions have no \`review\` field. Their interpretive points are listed at the end of this document.
`;

for (const [heading, list] of [
  ["Needs review", needs],
  ["Verified, with notes worth a look", verified],
]) {
  md += `\n## ${heading}\n`;
  for (const group of [...new Set(list.map((e) => e.group))]) {
    md += `\n### ${group}\n`;
    for (const entry of list.filter((e) => e.group === group)) {
      md += `\n#### ${entry.title}\n\n\`${entry.file}\` · ${entry.status}\n\n`;
      md += entry.notes.length
        ? entry.notes.map((n) => `- **${n.where}:** ${n.note}${n.resolution ? `\n  - *Resolution:* ${n.resolution}` : "\n  - *Resolution:* none recorded"}`).join("\n") + "\n"
        : "_No notes._\n";
    }
  }
}

md += `
## Connect with Christ sessions

\`src/content/connect/sessions.json\` has no \`review\` field. Its interpretive points were reviewed before release and resolved as follows:

- \`not-my-will\` (*Qualified*): the insight says the revelation in Doctrine and Covenants 19 doesn't name a place, and that many readers connect it with Luke's account.
- \`borne-our-griefs\` (*Qualified*): Isaiah 53 is introduced as Isaiah's words about one who would bear others' griefs; that Abinadi taught they speak of Christ (Mosiah 14–15) and Matthew saw them fulfilled (Matthew 8:16–17) is cited by reference.
- \`lovest-thou-me\` (*Qualified*): the link between the three questions and Peter's denials is offered only as a ponder question ("John doesn't say").
- \`what-will-ye\` (*Qualified*): says Matthew doesn't compare the two scenes or say why Jesus asked.
- \`jesus-wept\`, \`abide-in-me\`, \`receiveth-sinners\`, \`lord-save-me\` (*Resolved*): light interpretive glosses rephrased plainly to what the verses say.
- Every prayer line begins "If you'd like," and none asks for feelings or a report. Nothing was withheld.
`;

await writeFile(new URL("../docs/2.0/DOCTRINAL_REVIEW.md", import.meta.url), md);
console.log(`${entries.length} items (${needs.length} needs-review), ${totalNotes} notes → docs/2.0/DOCTRINAL_REVIEW.md`);
